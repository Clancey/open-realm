/* Shared, bounded staging buffer capacity - see bz_quest_vk_wc3.h's header
 * comment. 16MB covers this slice's largest single upload
 * (BZ_QUEST_WC3_MAX_TEXTURE_BYTES); a full model's combined vertex+index
 * arrays (<=~2.9MB at this slice's per-model caps) always fits inside it
 * too, so one shared buffer serves both upload kinds sequentially. */
enum { BZ_QUEST_VK_WC3_STAGING_BYTES = BZ_QUEST_WC3_MAX_TEXTURE_BYTES };

/* Raw MDX geoset/layer shading bit values this file reads from
 * bzQuestWc3LayerDesc_t::flags - mirrors games/warcraft-3/renderer/mdx/
 * r_mdx.h:27-35's mdxGeoFlags_t exactly (not #included directly: that
 * header pulls in renderer/r_local.h, the desktop engine's own internal
 * dependency surface, which this Quest-host module must stay free of -
 * see AGENTS.md's "Keep Android/OpenXR/Vulkan types out of shared bridge
 * headers" and this project's mirrored-constant precedent, e.g.
 * bz_quest_pure.c's BZ_QUEST_XR_COMPOSITION_LAYER_*_BIT_VALUE). */
enum {
    BZ_QUEST_MDX_GEO_TWOSIDED = 0x10,
    BZ_QUEST_MDX_GEO_NO_DEPTH_TEST = 0x40,
    BZ_QUEST_MDX_GEO_NO_DEPTH_SET = 0x80,
};

/* Mirrors platform/bridge/bz_tabletop_assets.h's bzTTBlendMode_t exactly.
 * Not #included directly for the same reason as the MDX_GEO_* bits above:
 * this module never touches the tabletop asset ABI (see this file's header
 * comment - only bz_quest_wc3_capture.c does), and bz_quest_wc3_render.h's
 * bzQuestWc3LayerDesc_t::blendMode already deliberately stores this as a
 * raw uint32_t rather than including that header either (same rationale,
 * see that field's comment). Cross-checked against the real enum by
 * bz_quest_wc3_capture.c's _Static_assert (the one file in this slice that
 * legitimately includes bz_tabletop_assets.h), so a future renumbering of
 * bzTTBlendMode_t fails the build here instead of silently mis-blending. */
enum {
    BZ_QUEST_TTA_BLEND_OPAQUE = 0,
    BZ_QUEST_TTA_BLEND_TRANSPARENT = 1,
    BZ_QUEST_TTA_BLEND_ALPHA = 2,
    BZ_QUEST_TTA_BLEND_ADDITIVE = 3,
    BZ_QUEST_TTA_BLEND_ADD_ALPHA = 4,
    BZ_QUEST_TTA_BLEND_MODULATE = 5,
    BZ_QUEST_TTA_BLEND_MODULATE_2X = 6,
};

static bool find_memory_type(VkPhysicalDevice physicalDevice, uint32_t typeBits,
                             VkMemoryPropertyFlags required, uint32_t *outIndex) {
    VkPhysicalDeviceMemoryProperties props;
    vkGetPhysicalDeviceMemoryProperties(physicalDevice, &props);
    for (uint32_t i = 0; i < props.memoryTypeCount; i++) {
        if (!(typeBits & (1u << i))) continue;
        if ((props.memoryTypes[i].propertyFlags & required) != required) continue;
        *outIndex = i;
        return true;
    }
    BZ_QUEST_LOGE("bz_quest_vk_wc3: no memory type matches bits=0x%x flags=0x%x", typeBits,
                  (unsigned)required);
    return false;
}

static bool create_shader_module(VkDevice device, const uint32_t *code, uint32_t codeLen,
                                 VkShaderModule *out) {
    VkShaderModuleCreateInfo info = {0};
    info.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    info.codeSize = codeLen;
    info.pCode = code;
    if (vkCreateShaderModule(device, &info, NULL, out) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateShaderModule failed");
        return false;
    }
    return true;
}

/* Runs `record` (which must vkCmdCopyBuffer/vkCmdCopyBufferToImage/
 * vkCmdPipelineBarrier from `vk3->stagingBuffer`) on vk3->uploadCommandBuffer
 * as a one-time-submit command buffer, then blocks until the queue is idle
 * before returning - mirrors bz_quest_vk_render_target()'s own
 * fence-wait-before-return discipline (see bz_quest_vk_wc3.h's top comment)
 * so no upload is ever left in-flight when this function returns; the
 * caller may immediately reuse the staging buffer for the next upload. */
typedef void (*bzQuestVkWc3RecordFn)(VkCommandBuffer cmd, void *ctx);
static bool run_one_time_upload(bzQuestVkWc3_t *vk3, bzQuestVkWc3RecordFn record, void *ctx) {
    if (vkResetCommandBuffer(vk3->uploadCommandBuffer, 0) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkResetCommandBuffer (upload) failed");
        return false;
    }
    VkCommandBufferBeginInfo beginInfo = {0};
    beginInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
    beginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    if (vkBeginCommandBuffer(vk3->uploadCommandBuffer, &beginInfo) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkBeginCommandBuffer (upload) failed");
        return false;
    }
    record(vk3->uploadCommandBuffer, ctx);
    if (vkEndCommandBuffer(vk3->uploadCommandBuffer) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkEndCommandBuffer (upload) failed");
        return false;
    }
    VkSubmitInfo submitInfo = {0};
    submitInfo.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    submitInfo.commandBufferCount = 1;
    submitInfo.pCommandBuffers = &vk3->uploadCommandBuffer;
    /* No fence handoff needed here (unlike bz_quest_vk_render_target()'s
     * per-eye XR_KHR_vulkan_enable2 contract) - this queue is not shared
     * with an XR compositor's own synchronization requirement, so a plain
     * vkQueueWaitIdle() is sufficient and simpler than a dedicated fence. */
    if (vkQueueSubmit(vk3->vk->queue, 1, &submitInfo, VK_NULL_HANDLE) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkQueueSubmit (upload) failed");
        return false;
    }
    if (vkQueueWaitIdle(vk3->vk->queue) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkQueueWaitIdle (upload) failed");
        return false;
    }
    return true;
}

/* Read-only cache lookup that never triggers a create() call - unlike
 * bz_quest_wc3_cache_acquire(), which unconditionally creates on a miss.
 * bz_quest_vk_wc3_render_target() must never itself trigger a new upload
 * (all uploads happen only via bz_quest_vk_wc3_capture_and_upload(), which
 * is the sole, per-frame-budgeted caller of cache_acquire() - see this
 * file's header comment); this reads bzQuestWc3Cache_t's public slots[]
 * array directly, the same "sibling module reaches into public fields"
 * pattern bz_quest_vk.c's own callers already use for bzQuestVk_t. */
static void *cache_find(const bzQuestWc3Cache_t *cache, const char *identity) {
    for (uint32_t i = 0; i < cache->capacity; i++) {
        if (cache->slots[i].occupied && bz_quest_wc3_identity_equal(cache->slots[i].key.identity, identity))
            return cache->slots[i].handle;
    }
    return NULL;
}

