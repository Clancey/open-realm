bool bz_quest_vk_wc3_create(const bzQuestVk_t *vk, bzQuestVkWc3_t *out) {
    memset(out, 0, sizeof(*out));
    out->vk = vk;

    VkDescriptorSetLayoutBinding binding = {0};
    binding.binding = 0;
    binding.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    binding.descriptorCount = 1;
    binding.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
    VkDescriptorSetLayoutCreateInfo layoutInfo = {0};
    layoutInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    layoutInfo.bindingCount = 1;
    layoutInfo.pBindings = &binding;
    if (vkCreateDescriptorSetLayout(vk->device, &layoutInfo, NULL, &out->descriptorSetLayout) !=
        VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateDescriptorSetLayout failed");
        goto fail;
    }

    {
        /* Sized to BZ_QUEST_VK_WC3_TEXTURE_DESCRIPTOR_POOL_CAPACITY (capacity
         * + 1 spare set), NOT the bare BZ_QUEST_VK_WC3_TEXTURE_CACHE_CAPACITY
         * - see that constant's doc comment in bz_quest_vk_wc3.h for why a
         * pool sized to exactly `capacity` sets deadlocks the texture cache
         * the first time a (capacity+1)-th distinct texture is requested. */
        VkDescriptorPoolSize poolSize = {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER,
                                        BZ_QUEST_VK_WC3_TEXTURE_DESCRIPTOR_POOL_CAPACITY};
        VkDescriptorPoolCreateInfo poolInfo = {0};
        poolInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
        poolInfo.flags = VK_DESCRIPTOR_POOL_CREATE_FREE_DESCRIPTOR_SET_BIT;
        poolInfo.maxSets = BZ_QUEST_VK_WC3_TEXTURE_DESCRIPTOR_POOL_CAPACITY;
        poolInfo.poolSizeCount = 1;
        poolInfo.pPoolSizes = &poolSize;
        if (vkCreateDescriptorPool(vk->device, &poolInfo, NULL, &out->descriptorPool) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateDescriptorPool failed");
            goto fail;
        }
    }

    {
        /* Single shared REPEAT-addressed linear sampler - see
         * bz_quest_wc3_render.h's texture wrap-mode evidence for why no
         * per-texture wrap configuration is needed this slice. */
        VkSamplerCreateInfo samplerInfo = {0};
        samplerInfo.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
        samplerInfo.magFilter = VK_FILTER_LINEAR;
        samplerInfo.minFilter = VK_FILTER_LINEAR;
        samplerInfo.addressModeU = VK_SAMPLER_ADDRESS_MODE_REPEAT;
        samplerInfo.addressModeV = VK_SAMPLER_ADDRESS_MODE_REPEAT;
        samplerInfo.addressModeW = VK_SAMPLER_ADDRESS_MODE_REPEAT;
        samplerInfo.maxLod = 0.25f;
        if (vkCreateSampler(vk->device, &samplerInfo, NULL, &out->sampler) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateSampler failed");
            goto fail;
        }
    }

    if (!create_palette_resources(out)) goto fail;

    if (!create_shader_module(vk->device, g_bz_quest_warcraft_vert_spv, g_bz_quest_warcraft_vert_spv_len,
                              &out->vertexShader))
        goto fail;
    if (!create_shader_module(vk->device, g_bz_quest_warcraft_frag_spv, g_bz_quest_warcraft_frag_spv_len,
                              &out->fragmentShader))
        goto fail;

    {
        /* Two non-overlapping ranges - see bz_quest_vk_wc3.h's push-constant
         * layout doc comment: 64 bytes of vertex-stage mvp at offset 0, 16
         * bytes of fragment-stage material params at offset 64. 80 bytes
         * total, safely under Vulkan's guaranteed-minimum 128-byte
         * maxPushConstantsSize. */
        VkPushConstantRange ranges[2];
        ranges[0].stageFlags = VK_SHADER_STAGE_VERTEX_BIT;
        ranges[0].offset = 0;
        ranges[0].size = sizeof(float) * 16;
        ranges[1].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
        ranges[1].offset = sizeof(float) * 16;
        ranges[1].size = sizeof(float) * 4;
        /* Set 0 = per-texture combined-image-sampler (existing 5A layout),
         * set 1 = the shared bone-palette dynamic-offset UBO (see
         * bzQuestVkWc3_t's paletteDescriptorSetLayout doc comment) - both
         * bound together by draw_layer()'s single vkCmdBindDescriptorSets
         * call. */
        VkDescriptorSetLayout setLayouts[2] = {out->descriptorSetLayout, out->paletteDescriptorSetLayout};
        VkPipelineLayoutCreateInfo layoutCreateInfo = {0};
        layoutCreateInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
        layoutCreateInfo.setLayoutCount = 2;
        layoutCreateInfo.pSetLayouts = setLayouts;
        layoutCreateInfo.pushConstantRangeCount = 2;
        layoutCreateInfo.pPushConstantRanges = ranges;
        if (vkCreatePipelineLayout(vk->device, &layoutCreateInfo, NULL, &out->pipelineLayout) !=
            VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreatePipelineLayout failed");
            goto fail;
        }
    }

    {
        VkBufferCreateInfo bufferInfo = {0};
        bufferInfo.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
        bufferInfo.size = BZ_QUEST_VK_WC3_STAGING_BYTES;
        bufferInfo.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
        bufferInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
        if (vkCreateBuffer(vk->device, &bufferInfo, NULL, &out->stagingBuffer) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateBuffer (staging) failed");
            goto fail;
        }
        VkMemoryRequirements memReq;
        vkGetBufferMemoryRequirements(vk->device, out->stagingBuffer, &memReq);
        uint32_t memoryTypeIndex = 0;
        if (!find_memory_type(vk->physicalDevice, memReq.memoryTypeBits,
                              VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
                              &memoryTypeIndex))
            goto fail;
        VkMemoryAllocateInfo allocInfo = {0};
        allocInfo.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
        allocInfo.allocationSize = memReq.size;
        allocInfo.memoryTypeIndex = memoryTypeIndex;
        if (vkAllocateMemory(vk->device, &allocInfo, NULL, &out->stagingMemory) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkAllocateMemory (staging) failed");
            goto fail;
        }
        if (vkBindBufferMemory(vk->device, out->stagingBuffer, out->stagingMemory, 0) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkBindBufferMemory (staging) failed");
            goto fail;
        }
    }

    {
        VkCommandBufferAllocateInfo cmdAllocInfo = {0};
        cmdAllocInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
        cmdAllocInfo.commandPool = vk->commandPool;
        cmdAllocInfo.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
        cmdAllocInfo.commandBufferCount = 1;
        if (vkAllocateCommandBuffers(vk->device, &cmdAllocInfo, &out->uploadCommandBuffer) !=
            VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkAllocateCommandBuffers (upload) failed");
            goto fail;
        }
    }

    if (!bz_quest_wc3_cache_init(&out->modelCache, BZ_QUEST_VK_WC3_MODEL_CACHE_CAPACITY,
                                model_cache_create, model_cache_destroy, out))
        goto fail;
    if (!bz_quest_wc3_cache_init(&out->textureCache, BZ_QUEST_VK_WC3_TEXTURE_CACHE_CAPACITY,
                                texture_cache_create, texture_cache_destroy, out))
        goto fail;

    BZ_QUEST_LOGI("bz_quest_vk_wc3: init complete");
    return true;

fail:
    BZ_QUEST_LOGE("bz_quest_vk_wc3: init failed - tearing down partial state");
    bz_quest_vk_wc3_destroy(out);
    return false;
}

