typedef struct {
    VkImage image;
} TextureUploadCtx_t;

static void record_texture_upload(VkCommandBuffer cmd, void *ctxPtr) {
    TextureUploadCtx_t *ctx = (TextureUploadCtx_t *)ctxPtr;
    VkImageMemoryBarrier toDst = {0};
    toDst.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
    toDst.oldLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    toDst.newLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
    toDst.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    toDst.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    toDst.image = ctx->image;
    toDst.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    toDst.subresourceRange.levelCount = 1;
    toDst.subresourceRange.layerCount = 1;
    toDst.dstAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
    vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, 0,
                        0, NULL, 0, NULL, 1, &toDst);
}

static void *texture_cache_create(const bzQuestWc3CacheKey_t *key, void *userdata) {
    (void)key;
    bzQuestVkWc3_t *vk3 = (bzQuestVkWc3_t *)userdata;
    uint32_t width = vk3->pendingTextureWidth, height = vk3->pendingTextureHeight;
    uint32_t rowBytes = vk3->pendingTextureRowBytes;
    const uint8_t *pixels = vk3->pendingTexturePixels;
    if (!pixels || width == 0 || height == 0) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: texture_cache_create called with no pending texture");
        return NULL;
    }
    VkDeviceSize tightBytes = (VkDeviceSize)width * 4 * height;
    if (tightBytes > BZ_QUEST_VK_WC3_STAGING_BYTES) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: texture '%s' %ux%u exceeds staging capacity",
                      vk3->pendingTextureIdentity ? vk3->pendingTextureIdentity : "?", width, height);
        return NULL;
    }

    VkImageCreateInfo imageInfo = {0};
    imageInfo.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    imageInfo.imageType = VK_IMAGE_TYPE_2D;
    imageInfo.format = VK_FORMAT_R8G8B8A8_UNORM;
    imageInfo.extent.width = width;
    imageInfo.extent.height = height;
    imageInfo.extent.depth = 1;
    imageInfo.mipLevels = 1;
    imageInfo.arrayLayers = 1;
    imageInfo.samples = VK_SAMPLE_COUNT_1_BIT;
    imageInfo.tiling = VK_IMAGE_TILING_OPTIMAL;
    imageInfo.usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;
    imageInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    imageInfo.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    VkImage image = VK_NULL_HANDLE;
    if (vkCreateImage(vk3->vk->device, &imageInfo, NULL, &image) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateImage failed");
        return NULL;
    }
    VkMemoryRequirements memReq;
    vkGetImageMemoryRequirements(vk3->vk->device, image, &memReq);
    uint32_t memoryTypeIndex = 0;
    VkDeviceMemory memory = VK_NULL_HANDLE;
    if (!find_memory_type(vk3->vk->physicalDevice, memReq.memoryTypeBits,
                          VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, &memoryTypeIndex)) {
        vkDestroyImage(vk3->vk->device, image, NULL);
        return NULL;
    }
    VkMemoryAllocateInfo allocInfo = {0};
    allocInfo.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    allocInfo.allocationSize = memReq.size;
    allocInfo.memoryTypeIndex = memoryTypeIndex;
    if (vkAllocateMemory(vk3->vk->device, &allocInfo, NULL, &memory) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkAllocateMemory (image) failed");
        vkDestroyImage(vk3->vk->device, image, NULL);
        return NULL;
    }
    if (vkBindImageMemory(vk3->vk->device, image, memory, 0) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkBindImageMemory failed");
        vkDestroyImage(vk3->vk->device, image, NULL);
        vkFreeMemory(vk3->vk->device, memory, NULL);
        return NULL;
    }

    void *mapped = NULL;
    if (vkMapMemory(vk3->vk->device, vk3->stagingMemory, 0, tightBytes, 0, &mapped) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkMapMemory (texture staging) failed");
        vkDestroyImage(vk3->vk->device, image, NULL);
        vkFreeMemory(vk3->vk->device, memory, NULL);
        return NULL;
    }
    /* Re-pack to a tight width*4 row stride: rowBytes may exceed width*4
     * (BLP row padding) but vkCmdCopyBufferToImage's bufferRowLength=0
     * default means "tightly packed", so the staging copy must already be
     * tightly packed regardless of the source's own row stride. */
    for (uint32_t y = 0; y < height; y++) {
        memcpy((uint8_t *)mapped + (size_t)y * width * 4, pixels + (size_t)y * rowBytes,
              (size_t)width * 4);
    }
    vkUnmapMemory(vk3->vk->device, vk3->stagingMemory);

    {
        TextureUploadCtx_t ctx = {image};
        /* record_texture_upload() only performs the UNDEFINED->TRANSFER_DST
         * barrier; the buffer->image copy and the final TRANSFER_DST->
         * SHADER_READ_ONLY barrier are recorded inline below (need
         * width/height, which run_one_time_upload()'s generic record
         * callback signature does not carry) - all three still happen
         * inside the SAME one-time-submit command buffer/queue-wait cycle
         * as record_texture_upload(), so this is one atomic upload, not
         * two. */
        if (vkResetCommandBuffer(vk3->uploadCommandBuffer, 0) != VK_SUCCESS) goto image_fail;
        VkCommandBufferBeginInfo beginInfo = {0};
        beginInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
        beginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
        if (vkBeginCommandBuffer(vk3->uploadCommandBuffer, &beginInfo) != VK_SUCCESS) goto image_fail;
        record_texture_upload(vk3->uploadCommandBuffer, &ctx);
        VkBufferImageCopy region = {0};
        region.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        region.imageSubresource.layerCount = 1;
        region.imageExtent.width = width;
        region.imageExtent.height = height;
        region.imageExtent.depth = 1;
        vkCmdCopyBufferToImage(vk3->uploadCommandBuffer, vk3->stagingBuffer, image,
                              VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);
        VkImageMemoryBarrier toShaderRead = {0};
        toShaderRead.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
        toShaderRead.oldLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
        toShaderRead.newLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
        toShaderRead.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        toShaderRead.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        toShaderRead.image = image;
        toShaderRead.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        toShaderRead.subresourceRange.levelCount = 1;
        toShaderRead.subresourceRange.layerCount = 1;
        toShaderRead.srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
        toShaderRead.dstAccessMask = VK_ACCESS_SHADER_READ_BIT;
        vkCmdPipelineBarrier(vk3->uploadCommandBuffer, VK_PIPELINE_STAGE_TRANSFER_BIT,
                            VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, 0, 0, NULL, 0, NULL, 1,
                            &toShaderRead);
        if (vkEndCommandBuffer(vk3->uploadCommandBuffer) != VK_SUCCESS) goto image_fail;
        VkSubmitInfo submitInfo = {0};
        submitInfo.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
        submitInfo.commandBufferCount = 1;
        submitInfo.pCommandBuffers = &vk3->uploadCommandBuffer;
        if (vkQueueSubmit(vk3->vk->queue, 1, &submitInfo, VK_NULL_HANDLE) != VK_SUCCESS)
            goto image_fail;
        if (vkQueueWaitIdle(vk3->vk->queue) != VK_SUCCESS) goto image_fail;
    }

    VkImageView view = VK_NULL_HANDLE;
    {
        VkImageViewCreateInfo viewInfo = {0};
        viewInfo.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
        viewInfo.image = image;
        viewInfo.viewType = VK_IMAGE_VIEW_TYPE_2D;
        viewInfo.format = VK_FORMAT_R8G8B8A8_UNORM;
        viewInfo.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        viewInfo.subresourceRange.levelCount = 1;
        viewInfo.subresourceRange.layerCount = 1;
        if (vkCreateImageView(vk3->vk->device, &viewInfo, NULL, &view) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateImageView failed");
            goto image_fail;
        }
    }

    VkDescriptorSet descriptorSet = VK_NULL_HANDLE;
    {
        VkDescriptorSetAllocateInfo allocInfo2 = {0};
        allocInfo2.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
        allocInfo2.descriptorPool = vk3->descriptorPool;
        allocInfo2.descriptorSetCount = 1;
        allocInfo2.pSetLayouts = &vk3->descriptorSetLayout;
        if (vkAllocateDescriptorSets(vk3->vk->device, &allocInfo2, &descriptorSet) != VK_SUCCESS) {
            BZ_QUEST_LOGE("bz_quest_vk_wc3: vkAllocateDescriptorSets failed");
            vkDestroyImageView(vk3->vk->device, view, NULL);
            goto image_fail;
        }
        VkDescriptorImageInfo imageDescInfo = {0};
        imageDescInfo.sampler = vk3->sampler;
        imageDescInfo.imageView = view;
        imageDescInfo.imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
        VkWriteDescriptorSet write = {0};
        write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
        write.dstSet = descriptorSet;
        write.dstBinding = 0;
        write.descriptorCount = 1;
        write.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        write.pImageInfo = &imageDescInfo;
        vkUpdateDescriptorSets(vk3->vk->device, 1, &write, 0, NULL);
    }

    bzQuestVkWc3Texture_t *out = (bzQuestVkWc3Texture_t *)malloc(sizeof(bzQuestVkWc3Texture_t));
    if (!out) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: malloc(bzQuestVkWc3Texture_t) failed");
        vkFreeDescriptorSets(vk3->vk->device, vk3->descriptorPool, 1, &descriptorSet);
        vkDestroyImageView(vk3->vk->device, view, NULL);
        goto image_fail;
    }
    out->image = image;
    out->memory = memory;
    out->view = view;
    out->descriptorSet = descriptorSet;
    return out;

image_fail:
    vkDestroyImage(vk3->vk->device, image, NULL);
    vkFreeMemory(vk3->vk->device, memory, NULL);
    return NULL;
}

static void texture_cache_destroy(void *handle, void *userdata) {
    bzQuestVkWc3_t *vk3 = (bzQuestVkWc3_t *)userdata;
    bzQuestVkWc3Texture_t *t = (bzQuestVkWc3Texture_t *)handle;
    if (t->descriptorSet != VK_NULL_HANDLE)
        vkFreeDescriptorSets(vk3->vk->device, vk3->descriptorPool, 1, &t->descriptorSet);
    if (t->view != VK_NULL_HANDLE) vkDestroyImageView(vk3->vk->device, t->view, NULL);
    if (t->image != VK_NULL_HANDLE) vkDestroyImage(vk3->vk->device, t->image, NULL);
    if (t->memory != VK_NULL_HANDLE) vkFreeMemory(vk3->vk->device, t->memory, NULL);
    free(t);
}

