/*
 * bz_quest_vk_wc3.c - see bz_quest_vk_wc3.h.
 *
 * Every VkResult this file checks is compared explicitly against
 * VK_SUCCESS - there is no "assume success" path, per AGENTS.md.
 *
 * -- Blend mode -> Vulkan mapping evidence (do not change without
 * re-deriving) --
 * games/warcraft-3/renderer/mdx/r_mdx_geoset.c's MDLX_SetBlendMode() is the
 * desktop engine's own OpenGL mapping for every bzTTBlendMode_t value; this
 * file's blend_state_for_mode() below reproduces it 1:1 in Vulkan terms
 * (glBlendFunc(src,dst) with no glBlendFuncSeparate call maps to identical
 * color/alpha blend factors - see that function's per-case comments):
 *
 *   BZ_TTA_BLEND_OPAQUE (glBlendFunc(ONE,ZERO), depthMask ON)       -> no blend, depth write on
 *   BZ_TTA_BLEND_TRANSPARENT (alpha-key: glBlendFunc(ONE,ZERO), depthMask ON,
 *     uAlphaCutoff 0.5 - renderer/r_shader.c:308)                  -> no blend, depth write on, shader alpha-discard@0.5
 *   BZ_TTA_BLEND_ALPHA (glBlendFunc(SRC_ALPHA,ONE_MINUS_SRC_ALPHA), depthMask OFF)
 *   BZ_TTA_BLEND_ADDITIVE (glBlendFunc(ONE,ONE), depthMask OFF)
 *   BZ_TTA_BLEND_ADD_ALPHA (glBlendFunc(SRC_ALPHA,ONE), depthMask OFF)
 *   BZ_TTA_BLEND_MODULATE (glBlendFunc(DST_COLOR,ZERO), depthMask OFF)
 *   BZ_TTA_BLEND_MODULATE_2X (glBlendFunc(DST_COLOR,SRC_COLOR), depthMask OFF)
 *
 * MDLX_IsBlendedLayer() (r_mdx_geoset.c:220-222) treats every blend mode
 * >= BZ_TTA_BLEND_ALPHA (2) as needing a back-to-front-sorted "blended
 * pass", drawn after every OPAQUE/TRANSPARENT layer - this file's draw loop
 * reproduces that exact two-pass split (see
 * bz_quest_vk_wc3_render_target()'s doc comment below).
 *
 * MDLX_ApplyLayerFlags() (r_mdx_geoset.c:208-218) is the source for this
 * file's cull/depth-test/depth-write flag handling: MODEL_GEO_TWOSIDED
 * disables culling, MODEL_GEO_NO_DEPTH_TEST disables the depth test,
 * MODEL_GEO_NO_DEPTH_SET forces depth-write off (only ever an additional
 * override, never a way to force depth-write back on over a blended mode's
 * own off default - see blend_state_for_mode()).
 *
 * This slice does not implement any lighting model (MODEL_GEO_UNSHADED is
 * not distinguished - see warcraft_vert.vert/warcraft_frag.frag's header
 * comments for why), so that one MDX layer flag bit has no effect here;
 * every other flag/blend-mode combination proven above is implemented.
 */
