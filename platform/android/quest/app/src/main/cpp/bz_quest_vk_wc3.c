typedef struct {
    uint32_t itemIndex, geosetIndex, layerIndex;
    float distanceSq;
} BlendedDraw_t;

static BlendedDraw_t s_blendedDraws[BZ_QUEST_WC3_MAX_RENDER_ITEMS * BZ_QUEST_WC3_MAX_GEOSETS_PER_MODEL];
static uint32_t s_blendedDrawCount;

static float distance_sq(const float world[16], const float cameraWorldPos[3]) {
    float dx = world[12] - cameraWorldPos[0];
    float dy = world[13] - cameraWorldPos[1];
    float dz = world[14] - cameraWorldPos[2];
    return dx * dx + dy * dy + dz * dz;
}

static int compare_blended_draw_farthest_first(const void *a, const void *b) {
    const BlendedDraw_t *ba = (const BlendedDraw_t *)a;
    const BlendedDraw_t *bb = (const BlendedDraw_t *)b;
    if (ba->distanceSq > bb->distanceSq) return -1;
    if (ba->distanceSq < bb->distanceSq) return 1;
    return 0;
}

