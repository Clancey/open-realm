/* blend_state_for_mode()'s single source of truth - see this file's header
 * comment for the exact desktop-engine evidence each row reproduces. */
static void blend_state_for_mode(uint32_t blendMode, VkPipelineColorBlendAttachmentState *outBlend,
                                 bool *outDepthWriteDefault) {
    memset(outBlend, 0, sizeof(*outBlend));
    outBlend->colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
                              VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
    outBlend->colorBlendOp = VK_BLEND_OP_ADD;
    outBlend->alphaBlendOp = VK_BLEND_OP_ADD;
    switch (blendMode) {
        case BZ_QUEST_TTA_BLEND_ALPHA:
            outBlend->blendEnable = VK_TRUE;
            outBlend->srcColorBlendFactor = outBlend->srcAlphaBlendFactor = VK_BLEND_FACTOR_SRC_ALPHA;
            outBlend->dstColorBlendFactor = outBlend->dstAlphaBlendFactor =
                VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
            *outDepthWriteDefault = false;
            break;
        case BZ_QUEST_TTA_BLEND_ADDITIVE:
            outBlend->blendEnable = VK_TRUE;
            outBlend->srcColorBlendFactor = outBlend->srcAlphaBlendFactor = VK_BLEND_FACTOR_ONE;
            outBlend->dstColorBlendFactor = outBlend->dstAlphaBlendFactor = VK_BLEND_FACTOR_ONE;
            *outDepthWriteDefault = false;
            break;
        case BZ_QUEST_TTA_BLEND_ADD_ALPHA:
            outBlend->blendEnable = VK_TRUE;
            outBlend->srcColorBlendFactor = outBlend->srcAlphaBlendFactor = VK_BLEND_FACTOR_SRC_ALPHA;
            outBlend->dstColorBlendFactor = outBlend->dstAlphaBlendFactor = VK_BLEND_FACTOR_ONE;
            *outDepthWriteDefault = false;
            break;
        case BZ_QUEST_TTA_BLEND_MODULATE:
            outBlend->blendEnable = VK_TRUE;
            outBlend->srcColorBlendFactor = outBlend->srcAlphaBlendFactor = VK_BLEND_FACTOR_DST_COLOR;
            outBlend->dstColorBlendFactor = outBlend->dstAlphaBlendFactor = VK_BLEND_FACTOR_ZERO;
            *outDepthWriteDefault = false;
            break;
        case BZ_QUEST_TTA_BLEND_MODULATE_2X:
            outBlend->blendEnable = VK_TRUE;
            outBlend->srcColorBlendFactor = outBlend->srcAlphaBlendFactor = VK_BLEND_FACTOR_DST_COLOR;
            outBlend->dstColorBlendFactor = outBlend->dstAlphaBlendFactor = VK_BLEND_FACTOR_SRC_COLOR;
            *outDepthWriteDefault = false;
            break;
        case BZ_QUEST_TTA_BLEND_OPAQUE:
        case BZ_QUEST_TTA_BLEND_TRANSPARENT:
        default:
            outBlend->blendEnable = VK_FALSE;
            *outDepthWriteDefault = true;
            break;
    }
}

static VkPipeline create_pipeline_variant(bzQuestVkWc3_t *vk3, uint32_t blendMode, bool twoSided,
                                          bool depthTestEnable, bool depthWriteEnable) {
    VkPipelineShaderStageCreateInfo stages[2];
    memset(stages, 0, sizeof(stages));
    stages[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
    stages[0].module = vk3->vertexShader;
    stages[0].pName = "main";
    stages[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
    stages[1].module = vk3->fragmentShader;
    stages[1].pName = "main";

    VkVertexInputBindingDescription binding = {0, sizeof(bzQuestWc3Vertex_t), VK_VERTEX_INPUT_RATE_VERTEX};
    /* Bone index (location 2) is VK_FORMAT_R8G8B8A8_UINT (read as GLSL
     * uvec4, unnormalized) and bone weight (location 3) is
     * VK_FORMAT_R8G8B8A8_UNORM (read as GLSL vec4, hardware-normalized
     * 0..255 -> 0.0..1.0) - this exactly reproduces the desktop engine's
     * own vertex-attribute format for the same two fields:
     * renderer/r_buffer.c:87-88's `glVertexAttribPointer(attrib_skin1, 4,
     * GL_UNSIGNED_BYTE, GL_FALSE, ...)` (unnormalized) and
     * `glVertexAttribPointer(attrib_boneWeight1, 4, GL_UNSIGNED_BYTE,
     * GL_TRUE, ...)` (normalized) respectively - see warcraft_vert.vert's
     * header comment for the matching skinning formula
     * (renderer/r_shader.c:227-229). */
    VkVertexInputAttributeDescription attrs[4] = {
        {0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(bzQuestWc3Vertex_t, position)},
        {1, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(bzQuestWc3Vertex_t, uv)},
        {2, 0, VK_FORMAT_R8G8B8A8_UINT, offsetof(bzQuestWc3Vertex_t, boneIndex)},
        {3, 0, VK_FORMAT_R8G8B8A8_UNORM, offsetof(bzQuestWc3Vertex_t, boneWeight)},
    };
    VkPipelineVertexInputStateCreateInfo vertexInput = {0};
    vertexInput.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
    vertexInput.vertexBindingDescriptionCount = 1;
    vertexInput.pVertexBindingDescriptions = &binding;
    vertexInput.vertexAttributeDescriptionCount = 4;
    vertexInput.pVertexAttributeDescriptions = attrs;

    VkPipelineInputAssemblyStateCreateInfo inputAssembly = {0};
    inputAssembly.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
    inputAssembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

    VkPipelineViewportStateCreateInfo viewportState = {0};
    viewportState.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
    viewportState.viewportCount = 1;
    viewportState.scissorCount = 1;

    VkPipelineRasterizationStateCreateInfo rasterization = {0};
    rasterization.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
    rasterization.polygonMode = VK_POLYGON_MODE_FILL;
    /* MODEL_GEO_TWOSIDED -> no culling; else back-face culling with the
     * same CCW front-face convention bz_quest_vk.c's own pipeline uses,
     * consistent with this slice's winding fix (see
     * bz_quest_wc3_render.h's coordinate evidence) - see this file's
     * header comment. */
    rasterization.cullMode = twoSided ? VK_CULL_MODE_NONE : VK_CULL_MODE_BACK_BIT;
    rasterization.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;
    rasterization.lineWidth = 1.0f;

    VkPipelineMultisampleStateCreateInfo multisample = {0};
    multisample.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
    multisample.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;

    VkPipelineDepthStencilStateCreateInfo depthStencil = {0};
    depthStencil.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
    depthStencil.depthTestEnable = depthTestEnable ? VK_TRUE : VK_FALSE;
    depthStencil.depthWriteEnable = depthWriteEnable ? VK_TRUE : VK_FALSE;
    depthStencil.depthCompareOp = VK_COMPARE_OP_LESS;

    VkPipelineColorBlendAttachmentState blendAttachment;
    bool depthWriteDefaultUnused = false;
    blend_state_for_mode(blendMode, &blendAttachment, &depthWriteDefaultUnused);

    VkPipelineColorBlendStateCreateInfo colorBlend = {0};
    colorBlend.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
    colorBlend.attachmentCount = 1;
    colorBlend.pAttachments = &blendAttachment;

    static const VkDynamicState kDynamicStates[2] = {VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
    VkPipelineDynamicStateCreateInfo dynamicState = {0};
    dynamicState.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
    dynamicState.dynamicStateCount = 2;
    dynamicState.pDynamicStates = kDynamicStates;

    VkGraphicsPipelineCreateInfo pipelineCreateInfo = {0};
    pipelineCreateInfo.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
    pipelineCreateInfo.stageCount = 2;
    pipelineCreateInfo.pStages = stages;
    pipelineCreateInfo.pVertexInputState = &vertexInput;
    pipelineCreateInfo.pInputAssemblyState = &inputAssembly;
    pipelineCreateInfo.pViewportState = &viewportState;
    pipelineCreateInfo.pRasterizationState = &rasterization;
    pipelineCreateInfo.pMultisampleState = &multisample;
    pipelineCreateInfo.pDepthStencilState = &depthStencil;
    pipelineCreateInfo.pColorBlendState = &colorBlend;
    pipelineCreateInfo.pDynamicState = &dynamicState;
    pipelineCreateInfo.layout = vk3->pipelineLayout;
    pipelineCreateInfo.renderPass = vk3->vk->renderPass;
    pipelineCreateInfo.subpass = 0;

    VkPipeline pipeline = VK_NULL_HANDLE;
    if (vkCreateGraphicsPipelines(vk3->vk->device, VK_NULL_HANDLE, 1, &pipelineCreateInfo, NULL,
                                  &pipeline) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateGraphicsPipelines (variant) failed");
        return VK_NULL_HANDLE;
    }
    return pipeline;
}

static VkPipeline get_or_create_pipeline_variant(bzQuestVkWc3_t *vk3, uint32_t blendMode,
                                                 bool twoSided, bool depthTestEnable,
                                                 bool depthWriteEnable) {
    for (uint32_t i = 0; i < vk3->pipelineVariantCount; i++) {
        bzQuestVkWc3PipelineVariant_t *v = &vk3->pipelineVariants[i];
        if (v->blendMode == blendMode && v->twoSided == twoSided &&
            v->depthTestEnable == depthTestEnable && v->depthWriteEnable == depthWriteEnable)
            return v->pipeline;
    }
    if (vk3->pipelineVariantCount >= BZ_QUEST_VK_WC3_MAX_PIPELINE_VARIANTS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: pipeline variant cache exhausted (%u) - reusing variant 0",
                      (uint32_t)BZ_QUEST_VK_WC3_MAX_PIPELINE_VARIANTS);
        return vk3->pipelineVariantCount > 0 ? vk3->pipelineVariants[0].pipeline : VK_NULL_HANDLE;
    }
    VkPipeline pipeline = create_pipeline_variant(vk3, blendMode, twoSided, depthTestEnable,
                                                  depthWriteEnable);
    if (pipeline == VK_NULL_HANDLE) return VK_NULL_HANDLE;
    bzQuestVkWc3PipelineVariant_t *v = &vk3->pipelineVariants[vk3->pipelineVariantCount++];
    v->blendMode = blendMode;
    v->twoSided = twoSided;
    v->depthTestEnable = depthTestEnable;
    v->depthWriteEnable = depthWriteEnable;
    v->pipeline = pipeline;
    return pipeline;
}

