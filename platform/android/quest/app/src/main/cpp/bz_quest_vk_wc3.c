typedef struct {
    bzQuestVkWc3_t *vk3;
    uint32_t vertexBytes;
    uint32_t indexBytes;
    VkBuffer vertexBuffer, indexBuffer;
} ModelUploadCtx_t;

static void record_model_upload(VkCommandBuffer cmd, void *ctxPtr) {
    ModelUploadCtx_t *ctx = (ModelUploadCtx_t *)ctxPtr;
    VkBufferCopy vertexCopy = {0, 0, ctx->vertexBytes};
    vkCmdCopyBuffer(cmd, ctx->vk3->stagingBuffer, ctx->vertexBuffer, 1, &vertexCopy);
    VkBufferCopy indexCopy = {ctx->vertexBytes, 0, ctx->indexBytes};
    vkCmdCopyBuffer(cmd, ctx->vk3->stagingBuffer, ctx->indexBuffer, 1, &indexCopy);
}

static bool create_device_local_buffer(bzQuestVkWc3_t *vk3, VkDeviceSize size,
                                       VkBufferUsageFlags usage, VkBuffer *outBuffer,
                                       VkDeviceMemory *outMemory) {
    VkBufferCreateInfo bufferInfo = {0};
    bufferInfo.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    bufferInfo.size = size;
    bufferInfo.usage = usage;
    bufferInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    if (vkCreateBuffer(vk3->vk->device, &bufferInfo, NULL, outBuffer) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkCreateBuffer failed");
        return false;
    }
    VkMemoryRequirements memReq;
    vkGetBufferMemoryRequirements(vk3->vk->device, *outBuffer, &memReq);
    uint32_t memoryTypeIndex = 0;
    if (!find_memory_type(vk3->vk->physicalDevice, memReq.memoryTypeBits,
                          VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, &memoryTypeIndex)) {
        vkDestroyBuffer(vk3->vk->device, *outBuffer, NULL);
        *outBuffer = VK_NULL_HANDLE;
        return false;
    }
    VkMemoryAllocateInfo allocInfo = {0};
    allocInfo.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    allocInfo.allocationSize = memReq.size;
    allocInfo.memoryTypeIndex = memoryTypeIndex;
    if (vkAllocateMemory(vk3->vk->device, &allocInfo, NULL, outMemory) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkAllocateMemory failed");
        vkDestroyBuffer(vk3->vk->device, *outBuffer, NULL);
        *outBuffer = VK_NULL_HANDLE;
        return false;
    }
    if (vkBindBufferMemory(vk3->vk->device, *outBuffer, *outMemory, 0) != VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkBindBufferMemory failed");
        vkDestroyBuffer(vk3->vk->device, *outBuffer, NULL);
        vkFreeMemory(vk3->vk->device, *outMemory, NULL);
        *outBuffer = VK_NULL_HANDLE;
        *outMemory = VK_NULL_HANDLE;
        return false;
    }
    return true;
}

static void *model_cache_create(const bzQuestWc3CacheKey_t *key, void *userdata) {
    (void)key;
    bzQuestVkWc3_t *vk3 = (bzQuestVkWc3_t *)userdata;
    const bzQuestWc3Model_t *model = vk3->pendingModel;
    if (!model) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: model_cache_create called with no pending model");
        return NULL;
    }
    VkDeviceSize vertexBytes = (VkDeviceSize)model->meta.vertexCount * sizeof(bzQuestWc3Vertex_t);
    VkDeviceSize indexBytes = (VkDeviceSize)model->meta.indexCount * sizeof(uint32_t);
    if (vertexBytes == 0 || indexBytes == 0 ||
        vertexBytes + indexBytes > BZ_QUEST_VK_WC3_STAGING_BYTES) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: model '%s' has empty or oversized geometry (%llu+%llu bytes)",
                      model->meta.identity, (unsigned long long)vertexBytes,
                      (unsigned long long)indexBytes);
        return NULL;
    }

    VkBuffer vertexBuffer = VK_NULL_HANDLE, indexBuffer = VK_NULL_HANDLE;
    VkDeviceMemory vertexMemory = VK_NULL_HANDLE, indexMemory = VK_NULL_HANDLE;
    if (!create_device_local_buffer(vk3, vertexBytes,
                                    VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT,
                                    &vertexBuffer, &vertexMemory))
        return NULL;
    if (!create_device_local_buffer(vk3, indexBytes,
                                    VK_BUFFER_USAGE_INDEX_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT,
                                    &indexBuffer, &indexMemory)) {
        vkDestroyBuffer(vk3->vk->device, vertexBuffer, NULL);
        vkFreeMemory(vk3->vk->device, vertexMemory, NULL);
        return NULL;
    }

    void *mapped = NULL;
    if (vkMapMemory(vk3->vk->device, vk3->stagingMemory, 0, vertexBytes + indexBytes, 0, &mapped) !=
        VK_SUCCESS) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: vkMapMemory (model staging) failed");
        goto fail;
    }
    memcpy(mapped, model->vertices, (size_t)vertexBytes);
    memcpy((uint8_t *)mapped + vertexBytes, model->indices, (size_t)indexBytes);
    vkUnmapMemory(vk3->vk->device, vk3->stagingMemory);

    {
        ModelUploadCtx_t ctx = {vk3, (uint32_t)vertexBytes, (uint32_t)indexBytes, vertexBuffer,
                                indexBuffer};
        if (!run_one_time_upload(vk3, record_model_upload, &ctx)) goto fail;
    }

    bzQuestVkWc3Model_t *out = (bzQuestVkWc3Model_t *)malloc(sizeof(bzQuestVkWc3Model_t));
    if (!out) {
        BZ_QUEST_LOGE("bz_quest_vk_wc3: malloc(bzQuestVkWc3Model_t) failed");
        goto fail;
    }
    out->vertexBuffer = vertexBuffer;
    out->indexBuffer = indexBuffer;
    out->vertexMemory = vertexMemory;
    out->indexMemory = indexMemory;
    out->meta = model->meta;
    return out;

fail:
    vkDestroyBuffer(vk3->vk->device, vertexBuffer, NULL);
    vkDestroyBuffer(vk3->vk->device, indexBuffer, NULL);
    vkFreeMemory(vk3->vk->device, vertexMemory, NULL);
    vkFreeMemory(vk3->vk->device, indexMemory, NULL);
    return NULL;
}

static void model_cache_destroy(void *handle, void *userdata) {
    bzQuestVkWc3_t *vk3 = (bzQuestVkWc3_t *)userdata;
    bzQuestVkWc3Model_t *m = (bzQuestVkWc3Model_t *)handle;
    if (m->vertexBuffer != VK_NULL_HANDLE) vkDestroyBuffer(vk3->vk->device, m->vertexBuffer, NULL);
    if (m->indexBuffer != VK_NULL_HANDLE) vkDestroyBuffer(vk3->vk->device, m->indexBuffer, NULL);
    if (m->vertexMemory != VK_NULL_HANDLE) vkFreeMemory(vk3->vk->device, m->vertexMemory, NULL);
    if (m->indexMemory != VK_NULL_HANDLE) vkFreeMemory(vk3->vk->device, m->indexMemory, NULL);
    /* Releases the bzQuestWc3ModelAnim_t arena transferred into this entry
     * by model_cache_create()'s `out->meta = model->meta` copy - see
     * model_ready_cb's ownership-transfer comment. NULL-safe. */
    bz_quest_wc3_model_anim_free((bzQuestWc3ModelAnim_t *)m->meta.anim);
    free(m);
}

